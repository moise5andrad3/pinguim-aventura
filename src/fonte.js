// Largura de um texto em px lógicos, para centralizar.
export function largura(txt, tam = 1) {
  return txt.length * 6 * tam - tam;
}

// Escreve com sombra opcional (cor da sombra ou null).
export function escrever(txt, x, y, cor, tam = 1, sombra = null) {
  if (sombra !== null) escrever(txt, x + tam, y + tam, sombra, tam, null);
  for (let i = 0; i < txt.length; i++) {
    const g = G[txt[i]] || G['?'];
    for (let l = 0; l < 7; l++) {
      for (let c = 0; c < 5; c++) {
        if (g[l][c] === '#') ret(x + (i * 6 + c) * tam, y + l * tam, tam, tam, cor);
      }
    }
  }
}

export function escreverCentro(txt, cx, y, cor, tam = 1, sombra = null) {
  escrever(txt, Math.round(cx - largura(txt, tam) / 2), y, cor, tam, sombra);
}
